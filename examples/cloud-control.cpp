// ---------------------------------------------------------------------------
// 一、把要远程控制的变量放在长期存活的位置
// ---------------------------------------------------------------------------
struct 配置
{
    bool  显示帧率 = false;      // 面板：开关 toggle
    float 菜单缩放 = 1.0f;       // 面板：滑动数值 range
    int   显示数量 = 10;         // 面板：滑动数值 range（整数）
    int   模式索引 = 0;          // 面板：下拉框 select
    std::string 提示文本 = "欢迎"; // 面板：文本 input
};

static 配置 g_配置;
static const std::vector<std::string> 模式列表 = {"稳定", "性能", "极限"};

// ---------------------------------------------------------------------------
// 二、按钮：把原来按钮里的业务抽成函数，再登记给云控
// ---------------------------------------------------------------------------
void 重置布局()
{
    // 这里写你原来按钮里的逻辑，例如恢复菜单位置 / 尺寸
}

// ---------------------------------------------------------------------------
// 三、初始化时绑定一次（值和后台上架的 key 必须一致）
// ---------------------------------------------------------------------------
void 绑定云控()
{
    // 中文接口
    JiYanSDK_API::云控::绑定开关("显示帧率", &g_配置.显示帧率);
    JiYanSDK_API::云控::绑定小数("菜单缩放", &g_配置.菜单缩放);
    JiYanSDK_API::云控::绑定整数("显示数量", &g_配置.显示数量);
    JiYanSDK_API::云控::绑定文本("提示文本", &g_配置.提示文本);
    JiYanSDK_API::云控::绑定下拉("模式", &g_配置.模式索引, 模式列表);
    JiYanSDK_API::云控::绑定按钮("重置布局", [] { 重置布局(); });

    // 英文接口完全等价，二选一即可：
    // RemoteConfig::GetInstance().BindValue("显示帧率", &g_配置.显示帧率);
    // RemoteConfig::GetInstance().BindSelect("模式", &g_配置.模式索引, 模式列表);
    // RemoteConfig::GetInstance().BindButton("重置布局", [] { 重置布局(); });
}

// ---------------------------------------------------------------------------
// 四、每帧调用一次（内部按服务端下发的间隔节流，不需要自己计时）
// ---------------------------------------------------------------------------
void 每帧()
{
    JiYanSDK_API::云控::更新();
}

// 面板点「立即刷新」时，让下一次拉取立刻发生（可选）
void 用户点了立刻同步()
{
    JiYanSDK_API::云控::立即同步();
}

// 排查用：最近一次失败原因；判断某个值是否被远程改过
void 排查()
{
    std::string 错误 = JiYanSDK_API::云控::最后错误();
    bool 改过 = JiYanSDK_API::云控::是否被远程覆盖("菜单缩放");
    (void)错误; (void)改过;
}

